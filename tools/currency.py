#!/usr/bin/env python3
"""Regenerate the currency resources from currency-api (https://latest.currency-api.pages.dev).

    tools/currency.py [names.json usd.json]

Without arguments both files are fetched. Writes `resources/currency.yaml` (the
units), `resources/currency-menu.txt` (the menu section) and `resources/rates.json`
(the bundled snapshot of rates, a baseline until live ones are set). Codes the
unit notation cannot hold (`1inch` starts with a digit) are left out.
"""
import json, sys, urllib.request, pathlib

BASE = "https://latest.currency-api.pages.dev/v1/currencies"
res = pathlib.Path(__file__).resolve().parent.parent / "resources"

def load(arg, url):
    if arg:
        return json.load(open(arg))
    with urllib.request.urlopen(url, timeout=30) as r:
        return json.load(r)

names = load(sys.argv[1] if len(sys.argv) > 2 else None, BASE + ".json")
rates = load(sys.argv[2] if len(sys.argv) > 2 else None, BASE + "/usd.json")

# Symbols written for a currency, as well as its code.
alts = {
    "USD": ["$"], "EUR": ["€"], "GBP": ["£"], "JPY": ["¥", "￥"], "INR": ["₹"],
    "KRW": ["₩"], "THB": ["฿"], "RUB": ["₽"], "TRY": ["₺"], "ILS": ["₪"],
    "PHP": ["₱"], "UAH": ["₴"], "VND": ["₫"], "NGN": ["₦"],
    "AUD": ["A$"], "CAD": ["C$"], "HKD": ["HK$"], "NZD": ["NZ$"], "SGD": ["S$"],
}
majors = ["USD", "EUR", "GBP", "JPY", "CHF", "CAD", "AUD", "CNY", "INR", "BTC", "ETH"]

# Codes that read as a unit, or a prefix and a unit, are left out, one a line.
skip = {l.split("#")[0].strip() for l in open(res.parent / "tools" / "currency-skip.txt")} - {""}
codes = sorted(c.upper() for c in names if c[0].isalpha() and c.upper() not in skip)
codes = [c for c in majors if c in codes] + [c for c in codes if c not in majors]

def label(code):
    n = names.get(code.lower(), "").strip() or code
    return n.replace('"', "'")

out = ["# Generated by tools/currency.py: do not edit by hand.",
       "# Each currency is defined over the US dollar, `$`, the base unit of the",
       "# currency dimension; its factor is a placeholder that the rates replace.", ""]
for c in codes:
    a = ", ".join(f'"{x}"' for x in alts.get(c, []))
    alt = f", alt: [{a}]" if a else ""
    if c == "USD":
        out.append(f'- {{symbol: USD, name: "US dollar", base: Currency, currency: true{alt}}}')
    else:
        out.append(f'- {{symbol: {c}, name: "{label(c)}", defn: USD, factor: "1", currency: true{alt}}}')
(res / "currency.yaml").write_text("\n".join(out) + "\n")

# The headings the picker files them under. What no list names is digital: the
# source is fiat, metals and coins, and the coins are the many.
regions = {
    "Europe": "EUR GBP CHF SEK NOK DKK ISK PLN CZK HUF RON BGN RSD ALL MKD BAM MDL UAH BYN BYR RUB TRY "
              "GIP GGP JEP IMP SPL VAL HRK ROL TRL ATS BEF DEM ESP FIM FRF GRD IEP ITL LUF NLG PTE "
              "CYP MTL SIT SKK EEK LTL LVL",
    "Americas": "USD CAD MXN BRL ARS CLP COP PEN UYU PYG BOB VES VEF VED VEB GTQ HNL NIO CRC PAB DOP CUP CUC "
                "JMD HTG TTD BBD BSD BZD XCD XCG KYD AWG ANG SRD SRG GYD BMD FKP SVC MXV",
    "Africa": "ZAR NGN EGP KES GHS GHC MAD TND DZD ETB UGX TZS ZMW ZMK BWP NAD MUR SCR MZN MZM AOA XOF XAF RWF MWK "
              "ZWL ZWD ZWG SDG SDD SSP LYD SLL SLE GMD GNF CDF BIF DJF ERN KMF LRD LSL MGA MGF MRU MRO STN STD CVE "
              "SZL SOS",
    "Asia-Pacific": "JPY CNY CNH INR KRW IDR THB VND MYR SGD PHP HKD TWD PKR BDT LKR NPR MMK KHR LAK MNT KZT UZS "
                    "KGS TJS TMT TMM AFN IRR IQD SAR AED QAR KWD BHD OMR JOD ILS LBP SYP YER AMD AZN AZM GEL BTN "
                    "MVR BND MOP KPW AUD NZD FJD PGK WST TOP VUV SBD TVD XPF",
    "Other": "XAU XAG XPT XPD XDR",
}
region_of = {code: name for name, text in regions.items() for code in text.split()}
sections = {name: [] for name in [*regions, "Digital"]}
for c in codes:
    sections[region_of.get(c, "Digital")].append(c)
# The majors lead each; the rest are in the order of their codes.
menu = []
# `Other` goes last: the registry files what no heading names under it, so it is
# kept the last heading.
for name in ["Americas", "Europe", "Africa", "Asia-Pacific", "Digital", "Other"]:
    menu += ["", f"== {name}"] + [f"{c} | {label(c)}" for c in sections[name]]
(res / "currency-menu.txt").write_text("\n".join(menu) + "\n")
print({k: len(v) for k, v in sections.items()})

snapshot = {"date": rates["date"], "usd": {k: v for k, v in rates["usd"].items()}}
(res / "rates.json").write_text(json.dumps(snapshot, separators=(",", ":")) + "\n")
print(len(codes), "currencies,", rates["date"])
